"""Rebuild game/js/questions.js from the CSVs in 'Question CSVs'.
Run from the project root:  python game/tools/build_questions.py
(The game reads questions.js so it can run straight from index.html without a web server.)"""
import csv, glob, json, os, re
root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
files = sorted(glob.glob(os.path.join(root, 'Question CSVs', '*.csv')))
rooms = []
for f in files:
    qs = []
    with open(f, encoding='utf-8-sig', newline='') as fh:
        for r in csv.DictReader(fh):
            v = r['Scam Value'].strip()
            m = re.fullmatch(r'\$?([\d,]+)', v)
            qs.append({
                'id': r['UID'].strip(),
                'q': r['Scenario Question'].strip(),
                'a': [r['Answer 1 (Don\'t Know)'].strip(), r['Answer 2 (Correct)'].strip(),
                      r['Answer 3 (Half-way)'].strip(), r['Answer 4 (Wrong)'].strip()],
                'v': int(m.group(1).replace(',', '')) if m else None,
            })
    rooms.append({'file': os.path.basename(f), 'type': qs[0] and next(csv.DictReader(open(f, encoding='utf-8-sig')))['Scam Type'], 'questions': qs})
out = os.path.join(root, 'game', 'js', 'questions.js')
with open(out, 'w', encoding='utf-8') as fh:
    fh.write('// AUTO-GENERATED by game/tools/build_questions.py - edit the CSVs, then re-run the script.\n')
    fh.write('window.QUESTION_BANK = ' + json.dumps(rooms, ensure_ascii=False) + ';\n')
print('wrote', out, [len(r['questions']) for r in rooms])
